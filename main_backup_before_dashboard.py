"""
main.py — MARK L (JARVIS) entry point and orchestrator.

This is the "brain wiring" of the app: it owns the live connection to
Gemini's real-time voice model, forwards microphone audio in and speaker
audio out, and — most importantly — implements tool use. Gemini is handed
a menu of callable tools (TOOL_DECLARATIONS below); when it decides
mid-conversation that it needs one (check the calendar, search the web,
control the browser, etc.), the response comes back as a function call
instead of speech, and JarvisLive._execute_tool() dispatches it to the
matching function in actions/*.py, runs it (usually on a background
thread so the voice stream never stalls), and hands the result back to
Gemini so it can keep talking with real information instead of a guess.

High-level structure:
  - Module-level helpers: config loading, transcript cleanup.
  - TOOL_DECLARATIONS: the JSON-schema menu of tools sent to Gemini.
  - JarvisLive: one instance per run — owns the live session, the audio
    pipeline, tool dispatch, and all the background tasks (morning
    briefing, proactive check-ins, system/health monitors).
  - main(): boots the PyQt6 UI (ui.py) and runs JarvisLive on a background
    thread so the UI's own event loop stays responsive.

ui.py is a separate, independent file — it only knows how to display
state and forward user input/clicks back via callbacks; it never talks to
Gemini directly. This file is the only thing that does.
"""

