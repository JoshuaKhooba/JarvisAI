def _load_system_prompt() -> str:
    """Loads the base system prompt from core/prompt.txt (identity, tone,
    ground rules), falling back to a minimal built-in prompt if that file
    is missing so the app can still boot."""
    try:
        return PROMPT_PATH.read_text(encoding="utf-8")
    except Exception:
        return (
            "You are JARVIS, Tony Stark's AI assistant. "
            "Be concise, direct, and always use the provided tools to complete tasks. "
            "Never simulate or guess results — always call the appropriate tool."
        )

_CTRL_RE = re.compile(r"<ctrl\d+>", re.IGNORECASE)

def _clean_transcript(text: str) -> str:
    """Strips model-internal control tokens and stray control characters out
    of Gemini's live transcription text before it's shown/logged."""
    text = _CTRL_RE.sub("", text)
    text = re.sub(r"[\x00-\x08\x0b-\x1f]", "", text)
    return text.strip()

